/// 外部 API を端末でどう抱えるかの既定値。**合成層が持つ分である。**
///
/// 1回の取得をどう待つか（タイムアウト・応答の大きさ・聞き直す間隔）は
/// `karita_public_api_client` の `defaults.dart` にある。**こちらは「取った後」の値**で、
/// どれだけ持つか・何件まで持つかを決める。層が違うので別に置く — クライアントは端末の事情を
/// 知らないし、知ると試験のたびに端末の設定が要る。
///
/// **どれも測る前の初期値である。** 実測で変える前提であり、`karita-book-cover-probe` の
/// 実験値（16冊・24時間・8秒）をそのまま持ってきたものではない。確定したら
/// `非公開資料:settings-and-parameters.md` へ移す。
library;

/// 取れた書誌を持つ長さ。
///
/// **長くしすぎない。** OpenBD は書誌を直すことがあり、利用者は「直ったはず」を確かめに来る。
const Duration bookRecordTtl = Duration(hours: 1);

/// 未収録を覚えておく長さ。**取れた書誌より短い。**
///
/// 未収録はしばらく変わらないが、**新刊が載るのを待っている利用者が居る。** 1時間持つと、
/// 載った直後に開いた人が「まだ無い」を見る。
const Duration bookNotListedTtl = Duration(minutes: 5);

/// 失敗を覚えておく長さ。**再描画のたびに外へ出さないためだけに持つ。**
///
/// 圏外から戻った利用者がすぐ試し直せる長さにする。長いと「直ったのに直らない」に見え、
/// 短いと画面を組み直すたびに要求が出る。
const Duration apiFailureTtl = Duration(seconds: 60);

/// 書誌を持つ件数。
const int maxBookRecords = 500;

/// 取れた書影を持つ長さ。
const Duration coverImageTtl = Duration(hours: 1);

/// 「URL は在るのに画像が無い」を覚えておく長さ。**一時的な失敗より長い。**
///
/// 404 は欠損であって不調ではない。取れた書影と同じ長さで持つ — 表紙が後から載ることは
/// あるが、その頻度は書誌が直る頻度と変わらない。
const Duration coverMissingTtl = Duration(hours: 1);

/// 書影のバイトを持つ合計。
///
/// **これは取ってきたバイトの勘定である。** 画面に出すために復号した後の絵は Flutter の
/// `ImageCache` が別に持つので、端末が実際に使う量はこれより多い。混ぜて数えない。
const int maxCoverBytes = 32 * 1024 * 1024;

/// 書影を持つ枚数。**バイトの上限に先に当たるのが普通である。**
const int maxCoverEntries = 500;

/// 蔵書の観測を持つ長さ。
///
/// **貸出状況は動く。** 長く持つと、借りられた直後の本が「貸出可」に見える。画面へ戻った
/// ときに聞き直すかどうかの鮮度の閾値も、いまはこれと同じにしてある。
const Duration holdingsTtl = Duration(minutes: 5);

/// 蔵書の観測を持つ組数。ISBN × 館で数える。
const int maxHoldingsEntries = 2000;

/// 図書館の候補を持つ長さ。**いちばん長い。**
///
/// 分館の増減は年単位でしか起きず、図書館を登録するのは端末で一度きりの作業である。
const Duration libraryCatalogTtl = Duration(hours: 24);

/// 図書館の候補を持つ都道府県の数。
///
/// **47 を全部は持たない。** 東京都だけで数百件が返る（2026-09-16 の実測では江東区の1市区で
/// 8システム19分館）。利用者が1回の登録で行き来するのはせいぜい隣接する2〜3県である。
const int maxLibraryPrefectures = 3;

/// 1回の塊で照会する冊数。**「上限」であって固定値ではない。**
///
/// 実際の塊は `min(これ, 予算 ÷ 館数)` である。**固定にすると館数6以上で壊れる** —
/// `CalilCheckClient.check()` は 冊数 × 館数 が `defaultBookRequestBudget`（50）を超えると
/// `ArgumentError` を投げるので、10冊固定は6館の端末で照会が始まらない。
///
/// **枠の消費はこの値で変わらない。** カーリルの上限は 1,000書籍リクエスト/時で、消費を
/// 決めるのは 冊数 × 館数 の積だけである（ポーリングは枠を消費しない）。刻みが変えるのは
/// **枠が尽きたときの配り方**である — 刻まなければ先着の数人が棚を全部埋めて残りが0冊に
/// なり、刻めば全員が最初の数冊を見られる。
///
/// **10 は同時30人・館数3を想定した値である。** その規模なら 30人 × 10冊 × 3館 = 900 で
/// 枠に収まり、通常の棚（10冊程度）は塊1つで終わる。想定を超える配布では、この値を下げる
/// のではなく端末ごとの appkey へ移す — 下げると「全員が数行しか見えない」を仕様として
/// 固定することになる。
const int holdingsChunkBooks = 10;

/// 塊と塊の間に待つ長さ。**バーストを抑えるためだけに待つ。**
///
/// 相手が `Cache` で即答した回は塊が1回のHTTPで終わるので、待たないと10塊が1秒以内に
/// 連射されうる。**聞き直しの間隔（2秒）と同じにしてある** — 照会中より速く外へ出ない、
/// というだけの決めである。
///
/// **枠のためではない。** 長くしても総消費は変わらず、100冊の走りが遅くなるだけである。
const Duration holdingsChunkPause = Duration(seconds: 2);

/// 塊をまたぐ走り全体の期限。
///
/// **`defaultCalilOverallTimeout`（60秒）は1セッションぶんである。** 10塊に分かれた走りには
/// 上限が無く、全塊が期限に達する最悪で10分走り続ける。
///
/// **[holdingsTtl] より短くしてある。** 同じ5分にすると、走り終わった時点で最初の塊の観測が
/// ちょうど期限切れになり、「確認 12:34」と出しているものが次の描画で消える。
const Duration holdingsRunDeadline = Duration(minutes: 3);

/// 上限に達したことを覚えておく長さ。**一般の失敗よりずっと長い。**
///
/// カーリルの枠は1時間単位なので、[apiFailureTtl]（60秒）で忘れると押し直すたびに外へ出て、
/// 尽きている枠をさらに削る。**この間は押しても照会に行かず、同じ案内を出す。**
///
/// 1時間にはしない。**枠は時間内に回復していく**（1時間前の消費から順に抜けていく）ので、
/// 尽きた瞬間から1時間待たせるのは長すぎる。
const Duration holdingsRateLimitedTtl = Duration(minutes: 10);
