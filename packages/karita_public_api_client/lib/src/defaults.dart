/// 接続先と、待ち・大きさ・回数の既定値。**散らさずここに集める。**
///
/// 値そのものより、**1箇所に在ることのほうが効く。** 各 adapter の引数の既定に直接書くと、
/// 「書影は何秒で切っているか」を知るのにクラスの定義を読む必要があり、変えるときは全部の
/// 呼び出し側を見て回ることになる。名前を付けておけば、設定の文書と突き合わせられる。
///
/// **ここに在るのは、この層が持てる値だけである。** キャッシュの期限・容量、同時実行数、
/// 再試行の方針はここに無い — それらは端末の事情で、合成層（`karita_app`）が決める。
/// この層は「1回の取得」しか知らないので、持ちようがない。
///
/// **どれも測る前の初期値である。** 実測で変えることを前提にしており、
/// `karita-book-cover-probe` の実験値（16冊・24時間・8秒）をそのまま持ってきたものではない。
/// 確定したら [設定とパラメータ] へ移す。
///
/// [設定とパラメータ]: 非公開資料:settings-and-parameters.md
library;

/// OpenBD の口。**公式の HTTPS で固定する** — 任意の proxy 設定を増やさない。
final Uri openBdApiBase = Uri.parse('https://api.openbd.jp/v1');

/// カーリルの口。`/check` と `/library` の両方がここから下がる。
final Uri calilApiBase = Uri.parse('https://api.calil.jp');

/// 書誌1件を待つ長さ。
const Duration defaultRecordTimeout = Duration(seconds: 10);

/// 書影1枚を待つ長さ。**書誌より長い。**
///
/// 相手が書誌の API ではなく取次や出版社のサーバであり、返ってくるのも桁違いに大きい。
/// 同じ値にすると、書誌が取れる回線で書影だけが落ち続ける。
const Duration defaultImageTimeout = Duration(seconds: 15);

/// カーリルの1要求ぶんを待つ長さ。**照会全体の期限とは別である。**
const Duration defaultCalilTimeout = Duration(seconds: 10);

/// 蔵書照会1回ぶんの全体の期限。
///
/// **達したら打ち切るが、それは「蔵書なし」ではない。** 取れている館の答えは残す。
/// 2秒間隔と合わせると20回ほど聞き直せる計算で、**完了せずに終わる回は普通に出る。**
const Duration defaultCalilOverallTimeout = Duration(seconds: 60);

/// 聞き直す間隔の下限。**公式が2秒以上を求めている。**
///
/// 上の初期値と違い、**これは測って変える値ではない。** 相手との約束である。
const Duration minPollInterval = Duration(seconds: 2);

/// 書誌の応答に許す大きさ。
const int defaultMaxRecordBytes = 1024 * 1024;

/// 書影1枚に許す大きさ。**超えたら読むのをやめる。**
///
/// probe が実機で通した値と同じである。表紙1枚がこれを超えるなら、40×60 の枠に出すものとして
/// 端末のメモリを預ける相手ではない。
const int defaultMaxImageBytes = 5 * 1024 * 1024;

/// カーリルの応答に許す大きさ。
///
/// `/library` は都道府県まるごとで数百件になりうるので、書誌より大きく取る。
const int defaultMaxCalilResponseBytes = 4 * 1024 * 1024;

/// `/library` を1回で取る上限。**これに当たったら切り詰めを利用者へ見せる。**
///
/// **2026-09-16 に 500 から上げた。測ったら足りなかった** — 都道府県まるごとを引くと
/// 東京都が 850行（310システム / 415KB）で、500 では切り詰められて `Tokyo_Koto` が
/// 500行の中に入る保証が無かった。次に大きいのは北海道の 425行で、他は 400行前後である。
/// 2000 は最大の県に対して倍以上の余裕がある値として採った。
///
/// **上限そのものが相手に在るわけではない。** 2000 を渡して 850行が返り、切り詰めの印も
/// 立たなかった。応答の大きさも [defaultMaxCalilResponseBytes] の 1/10 に収まる。
const int defaultLibraryLimit = 2000;

/// 1回の照会で使う書籍リクエストの目安。ISBN数 × systemid数で数える。
///
/// **HTTP の回数ではない。** 10冊を5館へ聞けば、要求が1本でも50書籍リクエストである。
/// 上限そのものはカーリル側が キー/IP あたりで持っており、こちらのこれは**アプリ側の設計の
/// 目安**である。超える対象をどう選び、どう分けるかは呼ぶ側（合成層）が決める。
const int defaultBookRequestBudget = 50;
